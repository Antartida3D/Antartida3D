import { useEffect, useState } from 'react';
import { posterReveal, POSTER_SOLID } from '@antartida/core';
import tallUrl from '@antartida/core/assets/loader-poster-tall.webp';
import wideUrl from '@antartida/core/assets/loader-poster-wide.webp';
import pole from '@antartida/core/assets/loader-poster.json' with { type: 'json' };
import { useMediaQuery } from '../hooks.ts';

interface PosterProps {
  /** Share of the loading steps done, 0 to 1: how far the colour has grown. */
  progress: number;
  /** Without colour: the 3D map did not load, only the sketch stays. */
  sketchOnly: boolean;
  /** Reduced motion: the colour does not animate, it comes whole when the loader is ready. */
  still: boolean;
}

/** How fast the colour grows toward its target (per second): slow enough to see it on a quick load. */
const EASE_RATE = 3;

const useViewportSize = () => {
  const read = () => ({ vw: window.innerWidth, vh: window.innerHeight });
  const [size, setSize] = useState(read);
  useEffect(() => {
    const on = () => setSize(read());
    window.addEventListener('resize', on);
    return () => window.removeEventListener('resize', on);
  }, []);
  return size;
};

/** Eases `target` in a frame loop: a CSS mask gradient does not transition on its own. */
function useEased(target: number, still: boolean): number {
  const [value, setValue] = useState(still ? target : 0);
  useEffect(() => {
    if (still) {
      setValue(target);
      return;
    }
    let id = 0;
    let last = performance.now();
    const tick = (now: number) => {
      const dt = Math.min(0.1, (now - last) / 1000);
      last = now;
      let done = false;
      setValue((v) => {
        const next = v + (target - v) * (1 - Math.exp(-dt * EASE_RATE));
        done = Math.abs(target - next) < 0.5;
        return done ? target : next;
      });
      if (!done) id = requestAnimationFrame(tick);
    };
    id = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(id);
  }, [target, still]);
  return value;
}

/**
 * The first frame of the 3D map (generated by `pnpm poster`) in two layers: a grey sketch and, over
 * it, the colour, which grows from the South Pole as the steps finish (#258). It is an image of the
 * app itself, not a datum: `alt=""` and hidden from screen readers.
 */
export function Poster({ progress, sketchOnly, still }: PosterProps) {
  const tall = useMediaQuery('(orientation: portrait)');
  const size = useViewportSize();
  const at = tall ? pole.tall : pole.wide;
  const radius = useEased(sketchOnly ? 0 : posterReveal(progress, size, at), still);
  const src = tall ? tallUrl : wideUrl;
  const mask = `radial-gradient(circle ${Math.round(radius)}px at ${at.x}% ${at.y}%, #000 ${POSTER_SOLID * 100}%, transparent)`;

  return (
    <div className="ld-poster" aria-hidden="true">
      <img className="ld-poster-sketch" src={src} alt="" decoding="async" />
      {!sketchOnly && radius > 0 && <img className="ld-poster-color" src={src} alt="" decoding="async" style={{ maskImage: mask, WebkitMaskImage: mask }} />}
      <svg className="ld-grid" focusable="false">
        {[14, 27, 42, 58].map((r) => <ellipse key={r} cx={`${at.x}%`} cy={`${at.y}%`} rx={`${r}%`} ry={`${r * 0.74}%`} />)}
        <line x1={`${at.x}%`} x2={`${at.x}%`} y1="0" y2="100%" />
        <line x1="0" x2="100%" y1={`${at.y}%`} y2={`${at.y}%`} />
      </svg>
    </div>
  );
}
